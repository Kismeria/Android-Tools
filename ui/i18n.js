const I18N = (() => {
  const letters = "A-Za-zА-Яа-яЁё";
  const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const rules = EN.slice()
    .sort((a, b) => b[0].length - a[0].length)
    .map(([ru, en]) => [new RegExp(`(?<![${letters}])${escape(ru)}(?![${letters}])`, "g"), en]);
  const cyr = /[А-Яа-яЁё]/;
  let lang = "ru";

  const tr = (text) => {
    if (lang !== "en" || !text || !cyr.test(text)) return text;
    let out = text;
    for (const [re, en] of rules) {
      if (!cyr.test(out)) break;
      out = out.replace(re, en);
    }
    return out;
  };

  const ATTRS = ["title", "placeholder"];
  const translateNode = (node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      const t = tr(node.nodeValue);
      if (t !== node.nodeValue) node.nodeValue = t;
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    if (node.matches?.("script, style, .console, .no-i18n")) return;
    for (const a of ATTRS) {
      const v = node.getAttribute?.(a);
      if (v && cyr.test(v)) node.setAttribute(a, tr(v));
    }
    if (node.dataset?.title && cyr.test(node.dataset.title)) node.dataset.title = tr(node.dataset.title);
    if (node.tagName === "TEMPLATE") translateNode(node.content);
    for (const child of node.childNodes) translateNode(child);
  };

  const observer = new MutationObserver((mutations) => {
    for (const m of mutations) {
      if (m.type === "characterData") translateNode(m.target);
      else if (m.type === "attributes") translateNode(m.target);
      else m.addedNodes.forEach(translateNode);
    }
  });

  return {
    get lang() { return lang; },
    get locale() { return lang === "en" ? "en-US" : "ru-RU"; },
    t: (text) => tr(text),
    apply(next) {
      lang = next === "en" ? "en" : "ru";
      document.documentElement.lang = lang;
      if (lang === "en") {
        translateNode(document.body);
        document.title = tr(document.title);
        observer.observe(document.body, {
          subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS,
        });
      }
    },
  };
})();
